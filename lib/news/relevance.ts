export type RelevanceVerdict = {
  economic: boolean;
  /** 판정 근거. 로그와 검수 화면에서 왜 걸렀는지 보여준다. */
  reason: string;
};

/**
 * 제목으로 경제 기사인지 판정한다.
 *
 * @param title 기사 제목 (네이버가 주는 원문. HTML 태그는 이미 제거된 상태)
 */
export function judgeEconomic(title: string): RelevanceVerdict {
  const text = normalize(title);
  if (!text) return { economic: false, reason: 'empty_title' };

  const economic = ECONOMIC.filter((term) => text.includes(normalize(term)));
  if (economic.length > 0) {
    return { economic: true, reason: `경제 신호: ${economic.slice(0, 3).join(', ')}` };
  }

  const blocked = NON_ECONOMIC.filter((term) => text.includes(normalize(term)));
  if (blocked.length > 0) {
    return { economic: false, reason: `비경제 신호: ${blocked.slice(0, 3).join(', ')}` };
  }

  // 신호가 없으면 통과시킨다.
  //
  // 기본 차단으로도 재봤는데 오차단이 컸다 — 실측 900건에서 "강진 덮친 실리콘
  // 아일랜드‥멈춰 선 TSMC", "호르무즈 유조선 피격", "에틸렌 스프레드 뚝뚝" 이
  // 전부 잘렸다. 경제 기사의 어휘는 좁지 않다.
  //
  // **이 필터는 최종 관문이 아니다.** 명백한 쓰레기(폭염·고양이 당뇨)만 수집 단계에서
  // 걷어내고, 진짜 판정은 공개 단계에서 한다 — 기사에 상장사 이름이 나오지 않으면
  // 애초에 종목을 붙일 수 없고, 붙일 수 없는 기사는 이 서비스에서 쓸모가 없다
  // (lib/events/state.ts 의 공개 게이트).
  return { economic: true, reason: '비경제 신호 없음' };
}

/** 정규화: 공백·기호를 지워 "최고 기온" 과 "최고기온" 을 같게 본다. */
function normalize(value: string): string {
  return value.toLowerCase().replace(/[\s··,.\-—–[\]()「」'"“”‘’]/g, '');
}
